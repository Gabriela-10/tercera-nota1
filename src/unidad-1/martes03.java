
public class martes03 {
    public static void main(String[] args) {
        byte contador = 1;
        while (contador <= 5) {
            System.out.println("contando: " + contador);
            contador++;
        }
        
        for (int i = 1; i <= 5; i++) {
            System.out.println("contando: " + i);
        }
    }
    
}
